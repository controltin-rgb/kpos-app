const SCOPE = ':not(.keep-light, .keep-light *)'
const rgb = (hex) => `rgb(${[1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(', ')})`
const esc = (cls) => cls.replace(/[[\]#/]/g, (c) => `\\${c}`)
const cases = (hex) => [...new Set([hex, hex.toLowerCase()])]
const rule = (selectors, decl) => `${selectors.map((s) => `html.dark ${s}${SCOPE}`).join(',\n')} {\n  ${decl}\n}\n`

let css = `/* GENERATED by scripts/gen-dark-css.mjs — do not edit by hand (pnpm theme:dark). */\n\n`
for (const [light, dark] of Object.entries(BG)) {
  const sel = cases(light).flatMap((h) => [`.${esc(`bg-[${h}]`)}`])
  sel.push(`[style*="background: ${rgb(light)}"]`, `[style*="background-color: ${rgb(light)}"]`)
  if (light === '#FFFFFF') sel.push('.bg-white')
  css += rule(sel, `background-color: ${dark} !important;`)
}
for (const [light, dark] of Object.entries(TEXT)) {
  const sel = cases(light).flatMap((h) => [`.${esc(`text-[${h}]`)}`, `[stroke="${h}"]`])
  // inline `color:` either starts the style attribute or follows "; " (never matches background-color)
  sel.push(`[style^="color: ${rgb(light)}"]`, `[style*="; color: ${rgb(light)}"]`)
  css += rule(sel, `color: ${dark} !important;`)
  css += rule(cases(light).map((h) => `[stroke="${h}"]`), `stroke: ${dark} !important;`)
  css += rule(cases(light).map((h) => `[fill="${h}"]`), `fill: ${dark} !important;`)
}
for (const [light, dark] of Object.entries(BORDER)) {
  const sel = cases(light).flatMap((h) => [`.${esc(`border-[${h}]`)}`])
  sel.push(`[style*="solid ${rgb(light)}"]`, `[style*="dashed ${rgb(light)}"]`, `[style*="border-color: ${rgb(light)}"]`)
  css += rule(sel, `border-color: ${dark} !important;`)
}

writeFileSync(join(import.meta.dirname, '../src/renderer/styles/dark.css'), css)
